    private void prepareForm() {
        if(kupac != null){
            txtIme.setText(kupac.getIme());
            txtPrezime.setText(kupac.getPrezime());
            txtEmail.setText(kupac.getEmail());
            txtBrojTelefona.setText(kupac.getBrojTelefona());
            cmbMesto.setSelectedItem(kupac.getMesto());
        }else{
        JOptionPane.showMessageDialog(this, "Neka greska", "Greska", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void populateCmb() {
        try {
            cmbMesto.setModel(new DefaultComboBoxModel<>(Controller.getInstance().ucitajMesta().toArray()));
            cmbMesto.setSelectedIndex(-1);
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, "Nije uspelo ucitavanje mesta.", "Greska", JOptionPane.ERROR_MESSAGE);
            ex.printStackTrace();
        }
    }
    

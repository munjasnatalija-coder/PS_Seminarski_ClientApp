    private void btnKreirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnKreirajActionPerformed
        try {
            String ime = txtIme.getText().trim();
            String prezime = txtPrezime.getText().trim();
            String email = txtEmail.getText().trim();
            String brojTelefona = txtBrojTelefona.getText().trim();
            Mesto mesto = (Mesto) cmbMesto.getSelectedItem();
            
            if(ime.isEmpty()|| prezime.isEmpty()||email.isEmpty()|| brojTelefona.isEmpty()){
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena.", "Greška", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            if(!(email.contains("@"))){
                JOptionPane.showMessageDialog(this, "Email nije u dobrom formatu.", "Greška", JOptionPane.ERROR_MESSAGE);
                return;
            }
            
            kupac.setBrojTelefona(brojTelefona);
            kupac.setEmail(email);
            kupac.setIme(ime);
            kupac.setPrezime(prezime);
            kupac.setMesto(mesto);
            
            Controller.getInstance().promeniKupca(kupac);
            
            PretraziKupcaForma prForma = (PretraziKupcaForma) getParent();
            prForma.refreshTable();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjen kupac.");
            this.dispose();
        } catch (Exception e) {
            e.printStackTrace();
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }//GEN-LAST:event_btnKreirajActionPerformed

